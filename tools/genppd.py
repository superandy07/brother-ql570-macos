#!/usr/bin/env python3
"""genppd.py - write ppd/Brother_QL-570.ppd for the native QL-570 driver.

Label sizes (names, page and printable dimensions) come from data/sizes.json,
taken from Brother's own QL-570 PPD so existing documents and presets keep
working. Option names match Brother's driver.
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILTER = "/Library/Printers/BrotherQL570Native/rastertoql570"


def pick(o, key, label, default, choices, order, code=lambda c: ""):
    o.append("*OpenUI *%s/%s: PickOne" % (key, label))
    o.append("*OrderDependency: %d AnySetup *%s" % (order, key))
    o.append("*Default%s: %s" % (key, default))
    for name, text in choices:
        o.append('*%s %s/%s: "%s"' % (key, name, text, code(name)))
    o.append("*CloseUI: *%s" % key)
    o.append("")


def main():
    sizes = json.load(open(os.path.join(ROOT, "data", "sizes.json")))
    o = [
        '*PPD-Adobe: "4.3"',
        '*% Brother QL-570 - native driver for macOS',
        '*% Generated by tools/genppd.py',
        '*FormatVersion: "4.3"',
        '*FileVersion: "1.0"',
        '*LanguageVersion: English',
        '*LanguageEncoding: ISOLatin1',
        '*PCFileName: "QL570N.PPD"',
        '*Manufacturer: "Brother"',
        '*Product: "(Brother QL-570)"',
        '*ModelName: "Brother QL-570"',
        '*ShortNickName: "Brother QL-570"',
        '*NickName: "Brother QL-570 (native)"',
        '*1284DeviceID: "MFG:Brother;CMD:PT-CBP;MDL:QL-570;CLS:PRINTER;"',
        '*PSVersion: "(3010.000) 0"',
        '*LanguageLevel: "3"',
        '*ColorDevice: False',
        '*DefaultColorSpace: Gray',
        '*FileSystem: False',
        '*Throughput: "1"',
        '*LandscapeOrientation: Plus90',
        '*TTRasterizer: Type42',
        '*cupsVersion: 1.4',
        '*cupsModelNumber: 0',
        '*cupsManualCopies: True',
        '*cupsSNMPSupplies: False',
        '*cupsLanguages: "en"',
        '*cupsFilter: "application/vnd.cups-raster 0 %s"' % FILTER,
        '',
        '*OpenGroup: General/General',
        '',
        '*OpenUI *PageSize/Media Size: PickOne',
        '*OrderDependency: 10 AnySetup *PageSize',
        '*DefaultPageSize: 62mm',
    ]
    for s in sizes:
        o.append('*PageSize %s/%s: "<</PageSize[%g %g]/ImagingBBox null>>setpagedevice"' % (s["name"], s["label"], s["w"], s["h"]))
    o += ['*CloseUI: *PageSize', '', '*OpenUI *PageRegion: PickOne',
          '*OrderDependency: 10 AnySetup *PageRegion', '*DefaultPageRegion: 62mm']
    for s in sizes:
        o.append('*PageRegion %s/%s: "<</PageSize[%g %g]/ImagingBBox null>>setpagedevice"' % (s["name"], s["label"], s["w"], s["h"]))
    o += ['*CloseUI: *PageRegion', '', '*DefaultImageableArea: 62mm']
    for s in sizes:
        o.append('*ImageableArea %s/%s: "%g %g %g %g"' % ((s["name"], s["label"]) + tuple(s["ia"])))
    o.append('*DefaultPaperDimension: 62mm')
    for s in sizes:
        o.append('*PaperDimension %s/%s: "%g %g"' % (s["name"], s["label"], s["w"], s["h"]))
    o.append('')

    on_off = [("ON", "On"), ("OFF", "Off")]
    pick(o, "BrAutoTapeCut", "Auto Cut", "ON", on_off, 41)
    pick(o, "BrCutLabel", "Cut every", "1", [(str(n), str(n)) for n in range(1, 100)], 42)
    pick(o, "BrCutAtEnd", "Cut at end", "ON", on_off, 43)
    pick(o, "BrRemoveBlkSpace", "Trim tape after data", "OFF", [("OFF", "Off"), ("ON", "On")], 45)
    o += ['*CloseGroup: General', '', '*OpenGroup: Quality/Quality', '']
    pick(o, "BrPriority", "Quality", "BrQuality",
         [("BrSpeed", "Give priority to print speed"), ("BrQuality", "Give priority to print quality")], 30)
    o.append('*OpenUI *Resolution/Resolution: PickOne')
    o.append('*OrderDependency: 10 AnySetup *Resolution')
    o.append('*DefaultResolution: 300x300dpi')
    for r in ("300x300", "300x600"):
        x, y = r.split("x")
        o.append('*Resolution %sdpi/%s x %s dpi: "<</HWResolution[%s %s]/cupsColorOrder 0/cupsColorSpace 3/cupsBitsPerColor 8>>setpagedevice"' % (r, x, y, x, y))
    o += ['*CloseUI: *Resolution', '']
    pick(o, "BrHalftonePattern", "Halftone", "BrErrorDiffusion",
         [("BrBinary", "For logo and text"), ("BrDither", "For text and graphics"),
          ("BrErrorDiffusion", "For general labels containing images")], 31)
    levels = [(str(n), str(n)) for n in range(20, -21, -1)]
    pick(o, "BrBrightness", "Brightness", "0", levels, 32)
    pick(o, "BrContrast", "Contrast", "0", levels, 33)
    pick(o, "BrMirror", "Mirror Printing", "OFF", [("OFF", "Off"), ("ON", "On")], 44)
    o += ['*CloseGroup: Quality', '',
          '*DefaultFont: Courier',
          '*Font Courier: Standard "(1.05)" Standard ROM',
          '*Font Helvetica: Standard "(1.05)" Standard ROM',
          '*% End of PPD', '']
    path = os.path.join(ROOT, "ppd", "Brother_QL-570.ppd")
    with open(path, "w", newline="\n") as f:
        f.write("\n".join(o))
    print("wrote", path)


if __name__ == "__main__":
    main()
